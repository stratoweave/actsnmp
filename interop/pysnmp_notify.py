#!/usr/bin/env python3
"""Independent SNMP notification sender for interop testing, based on pysnmp
(lextudio, 7.x).  Arguments deliberately mimic net-snmp snmptrap/snmpinform:

  pysnmp_notify.py [options] trap   RECEIVER ENTERPRISE AGENT-ADDR GENERIC SPECIFIC UPTIME [OID TYPE VALUE]...   (-v 1)
  pysnmp_notify.py [options] trap   RECEIVER UPTIME TRAPOID [OID TYPE VALUE]...                                  (-v 2c, -v 3)
  pysnmp_notify.py [options] inform RECEIVER UPTIME TRAPOID [OID TYPE VALUE]...                                  (-v 2c, -v 3)

RECEIVER: [udp:|udp6:]HOST[:PORT]  (default port 162), e.g. 127.0.0.1:16165, [::1]:16164
UPTIME:   sysUpTime.0 / v1 time-stamp in hundredths of a second; '' = time since
          this process started (like net-snmp; not deterministic)
options:  -v 1|2c|3  -c COMMUNITY  -t TIMEOUT(s, default 1)  -r RETRIES (default 5)
          -u USER -l noAuthNoPriv|authNoPriv|authPriv -a AUTH -A AUTHPASS -x PRIV -X PRIVPASS
          -n CONTEXT  -E CONTEXTENGINEID(hex)
          -e ENGINEID(hex)  the authoritative engine ID, as with net-snmp:
                            trap:   the sender's own snmpEngineID (default: generated by pysnmp)
                            inform: the receiver's engine ID (default: discovered)
          -Z BOOTS          v3 trap: our snmpEngineBoots (default 1; engineTime starts at 0
                            with every process, so any receiver accepts consecutive runs)
          -Ci               send an INFORM (snmptrap -Ci compatibility)
          --                end of options (for values starting with '-')
AUTH:     MD5 | SHA | SHA-224 | SHA-256 | SHA-384 | SHA-512
PRIV:     DES | AES | AES-192 | AES-256 | AES-192-C | AES-256-C (net-snmp names) | 3DES
          (AES-192/AES-256 = Blumenthal key extension, -C = Reeder; see pysnmp_client.py)
TYPE:     i INTEGER  u|g Gauge32  c Counter32  C Counter64  t TimeTicks  a IpAddress
          o OID  s STRING  x hex STRING  d decimal STRING  n NULL
          q Opaque (raw content, hex)
          F/D/I/U Opaque Float/Double/Int64/UInt64, encoded like net-snmp
              (e.g. F 1.0 -> Opaque 9F 78 04 3F 80 00 00, I 42 -> 9F 7A 01 2A)

v1 traps are encoded with pysnmp's SNMPv1 protocol module (all Trap-PDU fields
exactly as given), v2c/v3 notifications are sent with pysnmp's notification
originator (hlapi send_notification).  Nothing is printed on success.
Exit status: 0 = sent (trap) / acknowledged (inform), 1 = timeout or error
(message on stderr; an error-status in the inform response prints
"ERROR: <name>(<code>) index=<i>" on stdout), 2 = usage error.
"""
import asyncio
import os
import socket
import struct
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pysnmp_client as pc  # noqa: E402  (AUTH/PRIV tables, parse_oid/parse_agent)

from pyasn1.codec.ber import encoder  # noqa: E402
from pyasn1.type import univ  # noqa: E402
from pysnmp.hlapi.v3arch.asyncio import (  # noqa: E402
    CommunityData,
    ContextData,
    ObjectIdentity,
    ObjectType,
    SnmpEngine,
    Udp6TransportTarget,
    UdpTransportTarget,
    UsmUserData,
    send_notification,
)
from pysnmp.proto import api, rfc1902  # noqa: E402

START = time.monotonic()
SYS_UPTIME = (1, 3, 6, 1, 2, 1, 1, 3, 0)
SNMP_TRAP_OID = (1, 3, 6, 1, 6, 3, 1, 1, 4, 1, 0)
V1 = api.PROTOCOL_MODULES[api.SNMP_VERSION_1]

UsageError = pc.UsageError


# ------------------------------------------------------------- values ---

def ber_int(n, unsigned=False):
    if unsigned:
        b = n.to_bytes(max(1, (n.bit_length() + 7) // 8), "big")
        return b"\x00" + b if b[0] & 0x80 else b
    return n.to_bytes((n + (n < 0)).bit_length() // 8 + 1, "big", signed=True)


def opaque_special(t, v):
    """net-snmp OPAQUE_SPECIAL_TYPES encoding (asn_build_float & co)."""
    if t == "F":
        body, tag = struct.pack(">f", float(v)), 0x78
    elif t == "D":
        body, tag = struct.pack(">d", float(v)), 0x79
    elif t == "I":
        body, tag = ber_int(int(v)), 0x7A
    else:  # U
        body, tag = ber_int(int(v), unsigned=True), 0x7B
    return bytes([0x9F, tag, len(body)]) + body


def octets_from(t, v):
    if t == "s":
        return v.encode("utf-8")
    if t == "x":
        h = v.replace(" ", "").replace(":", "")
        if h.lower().startswith("0x"):
            h = h[2:]
        return bytes.fromhex(h)
    # d: decimal bytes "1.2.3" or "1 2 3"
    return bytes(int(x) for x in v.replace(".", " ").split())


def make_value(t, v, v1=False):
    """net-snmp type letter + text -> pysnmp value (SNMPv1 or SMIv2 classes)."""
    m = V1 if v1 else rfc1902
    try:
        if t == "i":
            return (V1.Integer if v1 else rfc1902.Integer32)(int(v))
        if t in ("u", "g"):
            return (V1.Gauge if v1 else rfc1902.Gauge32)(int(v))
        if t == "c":
            return (V1.Counter if v1 else rfc1902.Counter32)(int(v))
        if t == "C":
            if v1:
                raise UsageError("Counter64 cannot be sent in an SNMPv1 trap")
            return rfc1902.Counter64(int(v))
        if t == "t":
            return m.TimeTicks(int(v))
        if t == "a":
            return m.IpAddress(v)
        if t == "o":
            return m.ObjectIdentifier(pc.parse_oid(v))
        if t in ("s", "x", "d"):
            return m.OctetString(octets_from(t, v))
        if t == "n":
            return univ.Null("")
        if t == "q":
            return m.Opaque(octets_from("x", v))
        if t in ("F", "D", "I", "U"):
            return m.Opaque(opaque_special(t, v))
    except ValueError as e:
        raise UsageError("bad value %r for type %s: %s" % (v, t, e))
    raise UsageError("unknown TYPE %r" % t)


def varbinds(args, v1=False):
    if len(args) % 3:
        raise UsageError("varbinds must be OID TYPE VALUE triples")
    return [(pc.parse_oid(args[i]), make_value(args[i + 1], args[i + 2], v1))
            for i in range(0, len(args), 3)]


def uptime_value(s):
    if s == "":
        return int((time.monotonic() - START) * 100)
    try:
        return int(s)
    except ValueError:
        raise UsageError("bad UPTIME %r" % s)


# -------------------------------------------------------------- parsing ---

def parse_args(argv):
    o = {"version": "2c", "community": "public", "timeout": 1.0, "retries": 5,
         "user": None, "level": None, "auth": None, "authpass": None,
         "priv": None, "privpass": None, "context": "", "ctxengine": None,
         "engine": None, "boots": 1, "inform": False}
    flags = {"-v": "version", "-c": "community", "-t": "timeout", "-r": "retries",
             "-u": "user", "-l": "level", "-a": "auth", "-A": "authpass",
             "-x": "priv", "-X": "privpass", "-n": "context", "-E": "ctxengine",
             "-e": "engine", "-Z": "boots"}
    pos = []
    i = 0
    opts_done = False
    while i < len(argv):
        a = argv[i]
        if opts_done or a == "" or not a.startswith("-") or len(a) == 1 or a[1].isdigit():
            pos.append(a)
            i += 1
            continue
        if a == "--":
            opts_done = True
        elif a in ("-h", "--help"):
            sys.stdout.write(__doc__)
            sys.exit(0)
        elif a == "-Ci":
            o["inform"] = True
        elif a[:2] in flags:
            if len(a) > 2:
                o[flags[a[:2]]] = a[2:]
            elif i + 1 < len(argv):
                i += 1
                o[flags[a]] = argv[i]
            else:
                raise UsageError("option %s needs a value" % a)
        else:
            raise UsageError("unknown option %s" % a)
        i += 1
    try:
        o["timeout"] = float(o["timeout"])
        o["retries"] = int(o["retries"])
        o["boots"] = int(str(o["boots"]).split(",")[0])
    except ValueError as e:
        raise UsageError(str(e))
    if o["version"] not in ("1", "2c", "3"):
        raise UsageError("bad version %r (1|2c|3)" % o["version"])
    if len(pos) < 2:
        raise UsageError("need MODE (trap|inform) and RECEIVER")
    mode, receiver, rest = pos[0], pos[1], pos[2:]
    if mode not in ("trap", "inform"):
        raise UsageError("MODE must be trap or inform, not %r" % mode)
    if o["inform"]:
        mode = "inform"
    if mode == "inform" and o["version"] == "1":
        raise UsageError("SNMPv1 has no InformRequest")
    return o, mode, receiver, rest


def hexarg(s):
    s = s.strip()
    if s.lower().startswith("0x"):
        s = s[2:]
    try:
        return bytes.fromhex(s)
    except ValueError:
        raise UsageError("bad hex engine ID %r" % s)


def parse_receiver(spec):
    """[udp:|udp6:]HOST[:PORT] -> (host, port, ipv6); default port 162"""
    host, port, v6 = pc.parse_agent(spec)
    bare = spec.split(":", 1)[1] if spec.startswith(("udp:", "udp6:")) else spec
    explicit = ("]:" in bare) if bare.startswith("[") else (bare.count(":") == 1)
    return host, (port if explicit else 162), v6


# -------------------------------------------------------------- sending ---

def send_v1(o, receiver, rest):
    if len(rest) < 5:
        raise UsageError("v1 trap needs ENTERPRISE AGENT-ADDR GENERIC SPECIFIC UPTIME")
    ent, agent_addr, generic, specific, upt = rest[:5]
    pdu = V1.TrapPDU()
    V1.apiTrapPDU.set_defaults(pdu)
    try:
        V1.apiTrapPDU.set_enterprise(pdu, pc.parse_oid(ent))
        if agent_addr:
            V1.apiTrapPDU.set_agent_address(pdu, V1.IpAddress(agent_addr))
        V1.apiTrapPDU.set_generic_trap(pdu, int(generic))
        V1.apiTrapPDU.set_specific_trap(pdu, int(specific))
    except Exception as e:  # noqa: BLE001 - pyasn1 raises various errors
        raise UsageError("bad v1 trap field: %s" % e)
    V1.apiTrapPDU.set_timestamp(pdu, uptime_value(upt))
    V1.apiTrapPDU.set_varbinds(pdu, varbinds(rest[5:], v1=True))
    msg = V1.Message()
    V1.apiMessage.set_defaults(msg)
    V1.apiMessage.set_community(msg, o["community"])
    V1.apiMessage.set_pdu(msg, pdu)
    data = encoder.encode(msg)
    host, port, v6 = parse_receiver(receiver)
    fam = socket.AF_INET6 if v6 else socket.AF_INET
    with socket.socket(fam, socket.SOCK_DGRAM) as s:
        s.sendto(data, (host, port))
    return 0


def auth_data(o, mode):
    if o["version"] == "2c":
        return CommunityData(o["community"], mpModel=1)
    if not o["user"]:
        raise UsageError("-u USER required for -v 3")
    level = (o["level"] or "noAuthNoPriv").lower()
    if level not in ("noauthnopriv", "authnopriv", "authpriv"):
        raise UsageError("bad security level %r" % o["level"])
    kw = {}
    if mode == "inform" and o["engine"]:
        kw["securityEngineId"] = univ.OctetString(hexarg(o["engine"]))
    if level in ("authnopriv", "authpriv"):
        a = (o["auth"] or "MD5").upper()
        if a not in pc.AUTH:
            raise UsageError("unknown auth protocol %r" % o["auth"])
        if not o["authpass"]:
            raise UsageError("-A AUTHPASS required")
        kw["authKey"] = o["authpass"]
        kw["authProtocol"] = pc.AUTH[a]
    if level == "authpriv":
        p = (o["priv"] or "DES").upper()
        if p not in pc.PRIV:
            raise UsageError("unknown priv protocol %r" % o["priv"])
        if not o["privpass"]:
            raise UsageError("-X PRIVPASS required")
        kw["privKey"] = o["privpass"]
        kw["privProtocol"] = pc.PRIV[p]
    return UsmUserData(o["user"], **kw)


async def send_v2(o, mode, receiver, rest):
    if len(rest) < 2:
        raise UsageError("need UPTIME TRAPOID")
    upt, trapoid = rest[:2]
    vbs = []
    if upt != "":
        vbs.append((SYS_UPTIME, rfc1902.TimeTicks(uptime_value(upt))))
    vbs.append((SNMP_TRAP_OID, rfc1902.ObjectIdentifier(pc.parse_oid(trapoid))))
    vbs += varbinds(rest[2:])
    objs = [ObjectType(ObjectIdentity(univ.ObjectIdentifier(oid)), val) for oid, val in vbs]

    eng_kw = {}
    if o["version"] == "3" and mode == "trap" and o["engine"]:
        eng_kw["snmpEngineID"] = rfc1902.OctetString(hexarg(o["engine"]))
    eng = SnmpEngine(**eng_kw)
    if o["version"] == "3" and mode == "trap":
        # deterministic boots (pysnmp otherwise persists and increments it in $TMPDIR)
        (boots,) = eng.get_mib_builder().import_symbols("__SNMP-FRAMEWORK-MIB", "snmpEngineBoots")
        boots.syntax = boots.syntax.clone(o["boots"])
    auth = auth_data(o, mode)
    ctx_kw = {"contextName": o["context"].encode()}
    if o["ctxengine"]:
        ctx_kw["contextEngineId"] = univ.OctetString(hexarg(o["ctxengine"]))
    host, port, v6 = parse_receiver(receiver)
    tcls = Udp6TransportTarget if v6 else UdpTransportTarget
    target = await tcls.create((host, port), timeout=o["timeout"], retries=o["retries"])
    try:
        err_ind, err_stat, err_idx, _ = await send_notification(
            eng, auth, target, ContextData(**ctx_kw), mode, *objs, lookupMib=False)
        if mode == "trap":
            # let the dispatcher hand the datagram to the kernel before closing
            await asyncio.sleep(0.05)
    finally:
        try:
            eng.close_dispatcher()
        except Exception:  # noqa: BLE001
            pass
    if err_ind:
        msg = str(err_ind)
        if "timeout" in msg.lower() or "no snmp response" in msg.lower():
            sys.stderr.write("Timeout: No Response from %s.\n" % receiver)
        else:
            sys.stderr.write("Error: %s\n" % msg)
        return 1
    if int(err_stat):
        code = int(err_stat)
        sys.stdout.write("ERROR: %s(%d) index=%d\n" % (pc.ERROR_STATUS.get(code, "unknown"), code,
                                                       int(err_idx)))
        return 1
    return 0


def main(argv):
    try:
        o, mode, receiver, rest = parse_args(argv)
        if o["version"] == "1":
            return send_v1(o, receiver, rest)
        return asyncio.run(send_v2(o, mode, receiver, rest))
    except UsageError as e:
        sys.stderr.write("usage error: %s\n(see --help)\n" % e)
        return 2
    except OSError as e:
        sys.stderr.write("Error: %s\n" % e)
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
