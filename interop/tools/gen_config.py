#!/usr/bin/env python3
"""Generate the agent configuration files of the actsnmp interop lab.

  config/snmpd.conf        net-snmp agent
  config/snmpsim.args      snmpsim-command-responder --args-from-file
  config/snmptrapd.conf    net-snmp trap receiver (lab, udp and tcp 16164)
  config/snmptrapd-standin.conf
                           the same as a stand-in for the actsnmp receiver (udp/16165,
                           engine ID of actsnmp trapd), used by notifycheck.sh --selftest
  config/users.tsv         machine readable list of all SNMPv3 users

Run from anywhere:  python3 interop/tools/gen_config.py
The generated files are committed; re-run after editing this script.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
CONF = os.path.join(os.path.dirname(HERE), "config")

AUTH_PASS = "authpass123"
PRIV_PASS = "privpass123"

# net-snmp engine ID: 0x80001f88 (enterprise 8072, high bit set) + format 0x80
# (net-snmp specific) + "actsnmpd"
SNMPD_ENGINE_ID = "80001f8880" + b"actsnmpd".hex()
# snmpsim engine ID: 0x80004fb8 (enterprise 20408, pysnmp) + format 0x05
# (octets) + "actsnmpsim"
SNMPSIM_ENGINE_ID = "80004fb805" + b"actsnmpsim".hex()
# snmptrapd engine ID (for receiving v3 informs we only need the user)
SNMPTRAPD_ENGINE_ID = "80001f8880" + b"actsnmpt".hex()
# engine ID of the actsnmp receiver (actsnmp trapd, port 16165) and of the net-snmp
# stand-in that notifycheck.sh --selftest runs on that port
ACTSNMP_TRAPD_ENGINE_ID = "80001f8880" + b"actsnmpr".hex()
# fixed (authoritative) engine IDs of the v3 TRAP senders:
#   [0] net-snmp snmptrap -e ..., and actsnmp when sending to snmptrapd
#   [1] pysnmp_notify.py -e ...
TRAP_SENDER_ENGINE_IDS = ["8000000001020304", "8000000001020305"]

SNMPD_PORT = 16161
SNMPSIM_PORT = 16162
ACTON_AGENT_PORT = 16163  # actsnmp agent
SNMPTRAPD_PORT = 16164
ACTSNMP_TRAPD_PORT = 16165  # actsnmp trapd

# (suffix, net-snmp name, snmpsim/pysnmp name)
AUTHS = [
    ("md5", "MD5", "MD5"),
    ("sha", "SHA", "SHA"),
    ("sha224", "SHA-224", "SHA224"),
    ("sha256", "SHA-256", "SHA256"),
    ("sha384", "SHA-384", "SHA384"),
    ("sha512", "SHA-512", "SHA512"),
]

# (suffix, net-snmp name or None, snmpsim/pysnmp name or None)
#  aes192/aes256   = draft-blumenthal-aes-usm-04 key extension
#                    (net-snmp "AES-192"/"AES-256", pysnmp "AES192BLMT"/"AES256BLMT")
#  aes192c/aes256c = draft-reeder-snmpv3-usm-3desede key extension ("Cisco")
#                    (net-snmp "AES-192-C"/"AES-256-C", pysnmp "AES192"/"AES256")
PRIVS = [
    ("des", "DES", "DES"),
    ("aes", "AES", "AES"),
    ("aes192", "AES-192", "AES192BLMT"),
    ("aes256", "AES-256", "AES256BLMT"),
    ("aes192c", "AES-192-C", "AES192"),
    ("aes256c", "AES-256-C", "AES256"),
    ("3des", None, "3DES"),  # 3DES-EDE: snmpsim only, net-snmp has no 3DES
]


def users():
    """yield (name, level, auth_suffix, priv_suffix) for every user"""
    yield ("u_noauth", "noAuthNoPriv", None, None)
    for a, _, _ in AUTHS:
        yield ("u_" + a, "authNoPriv", a, None)
    for a, _, _ in AUTHS:
        for p, _, _ in PRIVS:
            yield ("u_%s_%s" % (a, p), "authPriv", a, p)


AUTHMAP = {a: (n, s) for a, n, s in AUTHS}
PRIVMAP = {p: (n, s) for p, n, s in PRIVS}

BASE = ".1.3.6.1.4.1.8072.9999.1"


def gen_snmpd():
    L = []
    w = L.append
    w("# GENERATED by interop/tools/gen_config.py - do not edit by hand")
    w("#")
    w("# net-snmp snmpd configuration for the actsnmp interop lab.")
    w("# Started as: snmpd -f -Lo -C -c /opt/actsnmp/config/snmpd.conf")
    w("")
    w("# listen on loopback only (container runs with --network host)")
    w("agentaddress udp:127.0.0.1:%d,udp6:[::1]:%d,tcp:127.0.0.1:%d,tcp6:[::1]:%d"
      % (SNMPD_PORT, SNMPD_PORT, SNMPD_PORT, SNMPD_PORT))
    w("")
    w("# fixed engine ID so that tests are deterministic")
    w("exactEngineID 0x%s" % SNMPD_ENGINE_ID)
    w("")
    w("# system group: sysDescr/sysObjectID are read-only, sysContact/sysName/")
    w("# sysLocation are initialised with the p* (persistent) tokens which keeps")
    w("# them WRITABLE via SNMP SET (community private / v3 users).")
    w("sysdescr actsnmp interop lab net-snmp agent")
    w("sysobjectid .1.3.6.1.4.1.8072.3.2.10")
    w("sysservices 72")
    w("psyscontact actsnmp-contact")
    w("psysname actsnmp-snmpd")
    w("psyslocation actsnmp-lab")
    w("")
    w("# deterministic test dataset (see interop/dataset/actsnmp_dataset.py)")
    w("pass_persist %s /opt/actsnmp/dataset/actsnmp_pass.py" % BASE)
    w("")
    w("# ---------------------------------------------------------------- VACM")
    w("view all     included .1")
    w("view rwview  included %s.20" % BASE)
    w("view rwview  included .1.3.6.1.2.1.1.4")
    w("view rwview  included .1.3.6.1.2.1.1.5")
    w("view rwview  included .1.3.6.1.2.1.1.6")
    w("view sysview included .1.3.6.1.2.1.1")
    w("")
    w("# SNMPv1/v2c communities")
    w("#   public  : read-only, everything")
    w("#   private : read everything, write rwview (dataset .20 + sysContact/Name/Location)")
    w("#   sysonly : read-only, system group only (view boundary tests)")
    for sec, comm in (("sec_public", "public"), ("sec_private", "private"),
                      ("sec_sysonly", "sysonly")):
        w("com2sec  %-12s default %s" % (sec, comm))
        w("com2sec6 %-12s default %s" % (sec, comm))
    for grp, sec in (("grp_public", "sec_public"), ("grp_private", "sec_private"),
                     ("grp_sysonly", "sec_sysonly")):
        w("group %-12s v1  %s" % (grp, sec))
        w("group %-12s v2c %s" % (grp, sec))
    w('access grp_public  "" any noauth exact all     none   none')
    w('access grp_private "" any noauth exact all     rwview none')
    w('access grp_sysonly "" any noauth exact sysview none   none')
    w("")
    w("# ------------------------------------------------------------ SNMPv3 USM")
    w("# auth password %s, priv password %s for every user" % (AUTH_PASS, PRIV_PASS))
    w("# Users can read everything and write rwview, at exactly their security level")
    w("# (a lower level request is rejected by VACM -> authorizationError).")
    for name, level, a, p in users():
        if a is None:
            w("createUser %s" % name)
        elif p is None:
            w("createUser %s %s %s" % (name, AUTHMAP[a][0], AUTH_PASS))
        else:
            pn = PRIVMAP[p][0]
            if pn is None:
                continue
            w("createUser %s %s %s %s %s" % (name, AUTHMAP[a][0], AUTH_PASS, pn, PRIV_PASS))
    w("# read-only v3 user (write attempts -> noAccess/notWritable)")
    w("createUser u_ro_sha_aes SHA %s AES %s" % (AUTH_PASS, PRIV_PASS))
    w("")
    for name, level, a, p in users():
        if p is not None and PRIVMAP[p][0] is None:
            continue
        grp = {"noAuthNoPriv": "grp_v3_noauth", "authNoPriv": "grp_v3_auth",
               "authPriv": "grp_v3_priv"}[level]
        w("group %s usm %s" % (grp, name))
    w("group grp_v3_ro usm u_ro_sha_aes")
    w('access grp_v3_noauth "" usm noauth exact all rwview none')
    w('access grp_v3_auth   "" usm auth   exact all rwview none')
    w('access grp_v3_priv   "" usm priv   exact all rwview none')
    w('access grp_v3_ro     "" usm priv   exact all none   none')
    w("")
    w("dontLogTCPWrappersConnects yes")
    return "\n".join(L) + "\n"


def gen_snmpsim():
    L = []
    w = L.append
    w("--v3-engine-id=%s" % SNMPSIM_ENGINE_ID)
    w("--data-dir=/opt/actsnmp/snmpsim/data")
    w("--agent-udpv4-endpoint=127.0.0.1:%d" % SNMPSIM_PORT)
    w("--agent-udpv6-endpoint=[::1]:%d" % SNMPSIM_PORT)
    for name, level, a, p in users():
        w("--v3-user=%s" % name)
        if a is not None:
            w("--v3-auth-key=%s" % AUTH_PASS)
            w("--v3-auth-proto=%s" % AUTHMAP[a][1])
        if p is not None:
            w("--v3-priv-key=%s" % PRIV_PASS)
            w("--v3-priv-proto=%s" % PRIVMAP[p][1])
    return "\n".join(L) + "\n"


def gen_snmptrapd(port=SNMPTRAPD_PORT, engine_id=SNMPTRAPD_ENGINE_ID, lab=True,
                  role="the lab trap receiver"):
    # the lab receiver listens on UDP and TCP, IPv4 and IPv6; the stand-in on udp:127.0.0.1 only
    L = []
    w = L.append
    w("# GENERATED by interop/tools/gen_config.py - do not edit by hand")
    if lab:
        w("# net-snmp snmptrapd: %s (traps/informs to udp and tcp %d)" % (role, port))
        w("snmpTrapdAddr udp:127.0.0.1:%d,udp6:[::1]:%d,tcp:127.0.0.1:%d,tcp6:[::1]:%d" % (port, port, port, port))
    else:
        w("# net-snmp snmptrapd: %s (traps/informs to udp/%d)" % (role, port))
        w("snmpTrapdAddr udp:127.0.0.1:%d" % port)
    w("# our engine ID: we are authoritative for v3 INFORMs")
    w("exactEngineID 0x%s" % engine_id)
    w("doNotRetainNotificationLogs yes")
    w("# One line per notification, tab separated, convertible to the canonical")
    w("# NOTIFICATION blocks with tools/snmptrapd2canon.py:")
    w("#   TRAP1 <src> <%P> enterprise= agent= generic= specific= uptime=<%T raw ticks> <varbinds...>")
    w("#   TRAP2 <src> <%P> <varbinds incl. sysUpTime.0 and snmpTrapOID.0...>")
    w("# Values: numeric OIDs, no enum labels, every OCTET STRING as unwrapped hex")
    w("# (single line).  %q prints the v1 specific-trap with a leading '.' when non-zero.")
    w("outputOption nex")
    w("[snmp] hexOutputLength 0")
    w("format1 TRAP1\\t%b\\t%P\\tenterprise=%N\\tagent=%a\\tgeneric=%w\\tspecific=%q\\tuptime=%T\\t%v\\n")
    w("format2 TRAP2\\t%b\\t%P\\t%v\\n")
    w("# Access control: only community 'public'; every user only at exactly its")
    w("# configured security level (authUser sets the minimum, the keys the maximum),")
    w("# so snmptrapd2canon.py can take the level from users.tsv.  Everything else")
    w("# is dropped silently.")
    w("authCommunity log,execute,net public")
    for name, level, a, p in users():
        if p is not None and PRIVMAP[p][0] is None:
            continue
        w("authUser log,execute,net %s %s" % (name, {"noAuthNoPriv": "noauth", "authNoPriv": "auth",
                                                      "authPriv": "priv"}[level]))
    w("# v3 INFORMs: we are authoritative, the plain createUser lines are used.")
    w("# v3 TRAPs: the SENDER is authoritative; snmptrapd needs the users per sender")
    w("# engine ID: 0x%s (net-snmp snmptrap -e, and our Client), 0x%s (pysnmp_notify -e)."
      % (TRAP_SENDER_ENGINE_IDS[0], TRAP_SENDER_ENGINE_IDS[1]))
    for name, level, a, p in users():
        if p is not None and PRIVMAP[p][0] is None:
            continue
        for eng in (None,) + tuple(TRAP_SENDER_ENGINE_IDS):
            e = "" if eng is None else "-e 0x%s " % eng
            if a is None:
                w("createUser %s%s" % (e, name))
            elif p is None:
                w("createUser %s%s %s %s" % (e, name, AUTHMAP[a][0], AUTH_PASS))
            else:
                w("createUser %s%s %s %s %s %s"
                  % (e, name, AUTHMAP[a][0], AUTH_PASS, PRIVMAP[p][0], PRIV_PASS))
    return "\n".join(L) + "\n"


def gen_snmptrapd_standin():
    return gen_snmptrapd(ACTSNMP_TRAPD_PORT, ACTSNMP_TRAPD_ENGINE_ID, lab=False,
                         role="stand-in for OUR receiver (actsnmp trapd), started by notifycheck.sh --selftest")


def gen_users_tsv():
    L = ["# user\tlevel\tauth(net-snmp)\tpriv(net-snmp)\tauth(pysnmp)\tpriv(pysnmp)"
         "\tauthpass\tprivpass\tsnmpd\tsnmpsim"]
    for name, level, a, p in users():
        an, asim = AUTHMAP[a] if a else ("-", "-")
        pn, psim = PRIVMAP[p] if p else ("-", "-")
        in_snmpd = "yes" if (p is None or pn is not None) else "no"
        L.append("\t".join([name, level, an, pn or "-", asim, psim,
                            AUTH_PASS if a else "-", PRIV_PASS if p else "-",
                            in_snmpd, "yes"]))
    L.append("\t".join(["u_ro_sha_aes", "authPriv", "SHA", "AES", "SHA", "AES",
                        AUTH_PASS, PRIV_PASS, "yes(read-only)", "no"]))
    return "\n".join(L) + "\n"


def main():
    os.makedirs(CONF, exist_ok=True)
    for fn, fun in (("snmpd.conf", gen_snmpd), ("snmpsim.args", gen_snmpsim),
                    ("snmptrapd.conf", gen_snmptrapd),
                    ("snmptrapd-standin.conf", gen_snmptrapd_standin),
                    ("users.tsv", gen_users_tsv)):
        with open(os.path.join(CONF, fn), "w") as f:
            f.write(fun())
        print("wrote", os.path.join(CONF, fn))


if __name__ == "__main__":
    main()
