#!/usr/bin/env bash
# Regenerate the committed dataset files for the actsnmp test agent:
#
#   actsnmp.snmprec       shared dataset B=.1.3.6.1.4.1.8072.9999.1 + snmpsim system group
#                         values + snmpEngineID.0 sentinel (plain snmprec, no variations)
#   write-rules.tsv       write rules of the B.20 objects (as snmpd/snmpsim enforce them)
#   pathological.snmprec  static part of the snmpsim pathological dataset
#
#   interop/dataset/regen.sh            regenerate (python3 on the host, else in the lab image)
#   interop/dataset/regen.sh --check    regenerate into a temp dir, diff against the committed
#                                       files, exit 1 if they differ (nothing is written)
#   interop/dataset/regen.sh --verify   --check + serve actsnmp.snmprec with snmpsim (throw-away
#                                       container, private network namespace) and compare
#                                       net-snmp walks/GETs with interop/expected/canon/*
#
# Generated by gen_snmprec.py --actsnmp from actsnmp_dataset.py (single source
# of truth); the system values come from expected/canon/snmpsim-system.txt.
set -euo pipefail
DATASET_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
. "$DATASET_DIR/../lib.sh"

mode="write"
case "${1:-}" in
    "") ;;
    --check) mode=check ;;
    --verify) mode=verify ;;
    -h|--help) sed -n '2,18p' "$0"; exit 0 ;;
    *) die "usage: $0 [--check|--verify]" ;;
esac

FILES=(actsnmp.snmprec write-rules.tsv pathological.snmprec)

gen() {  # outdir (absolute, below INTEROP_DIR or a temp dir)
    local out="$1"
    if command -v python3 >/dev/null 2>&1 && python3 -c 'import sys; sys.exit(sys.version_info < (3, 6))'; then
        python3 "$DATASET_DIR/gen_snmprec.py" --actsnmp "$out" \
            --system-canon "$INTEROP_DIR/expected/canon/snmpsim-system.txt" >&2
    else
        [ -n "$(image_id)" ] || "$INTEROP_DIR/build.sh" >&2
        docker run --rm --user "$(id -u):$(id -g)" \
            -v "$INTEROP_DIR:/interop:ro" -v "$out:/out" "$IMAGE" \
            python3 /interop/dataset/gen_snmprec.py --actsnmp /out \
            --system-canon /interop/expected/canon/snmpsim-system.txt >&2
    fi
}

if [ "$mode" = write ]; then
    gen "$DATASET_DIR"
    exit 0
fi

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
gen "$tmp"
rc=0
for f in "${FILES[@]}"; do
    if cmp -s "$tmp/$f" "$DATASET_DIR/$f"; then
        echo "dataset/$f up to date: PASS"
    else
        echo "dataset/$f differs from a fresh generation: **FAIL** (run interop/dataset/regen.sh)"
        diff -u "$DATASET_DIR/$f" "$tmp/$f" | head -20 || true
        rc=1
    fi
done
[ "$mode" = verify ] || exit $rc

# Serve the committed actsnmp.snmprec with snmpsim and check that independent
# tools see exactly the lab dataset.  Runs in its own network namespace (no
# --network host), so it cannot collide with the lab ports.
[ -n "$(image_id)" ] || "$INTEROP_DIR/build.sh" >&2
docker run --rm -i --user "$(id -u):$(id -g)" -e HOME=/tmp \
    -v "$INTEROP_DIR:/interop:ro" "$IMAGE" bash -s <<'EOF' || rc=1
set -u
B=.1.3.6.1.4.1.8072.9999.1
mkdir -p /tmp/data /tmp/cache
cp /interop/dataset/actsnmp.snmprec /tmp/data/public.snmprec
/opt/venv/bin/snmpsim-command-responder --data-dir=/tmp/data --cache-dir=/tmp/cache \
    --agent-udpv4-endpoint=127.0.0.1:16169 --logging-method=null >/dev/null 2>&1 &
for i in $(seq 1 60); do
    snmpget -v2c -c public -r0 -t1 127.0.0.1:16169 $B.1.1.0 >/dev/null 2>&1 && break
    sleep 0.5
done
rc=0
check() {  # name expected-file command...
    local name="$1" exp="$2"; shift 2
    if "$@" 2>&1 | netsnmp2canon | diff -u "$exp" - >/tmp/diff; then
        echo "snmpsim serving actsnmp.snmprec: $name: PASS"
    else
        echo "snmpsim serving actsnmp.snmprec: $name: **FAIL**"; head -20 /tmp/diff; rc=1
    fi
}
C="-On -Oe -Ox --hexOutputLength=0"
check "v2c bulkwalk of B = expected/canon/dataset.txt" /interop/expected/canon/dataset.txt \
    snmpbulkwalk -v2c -c public -Cr50 $C 127.0.0.1:16169 $B
check "v1 walk of B = expected/canon/dataset-v1.txt" /interop/expected/canon/dataset-v1.txt \
    snmpwalk -v1 -c public $C 127.0.0.1:16169 $B
check "system GET = expected/canon/snmpsim-system.txt" /interop/expected/canon/snmpsim-system.txt \
    snmpget -v2c -c public $C 127.0.0.1:16169 \
    1.3.6.1.2.1.1.1.0 1.3.6.1.2.1.1.2.0 1.3.6.1.2.1.1.4.0 1.3.6.1.2.1.1.5.0 1.3.6.1.2.1.1.6.0 1.3.6.1.2.1.1.7.0
exit $rc
EOF
exit $rc
